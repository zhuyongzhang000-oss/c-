/*
 * ══════════════════════════════════════════════════════════════════
 *  环02 自测：猜输出 + 判断对错（运行 ring02_quiz 自动判分）
 * ══════════════════════════════════════════════════════════════════
 *  做法同环01：
 *  一、猜输出：把 OUT 会输出的内容写进下一行 GUESS 的引号里（空格要写准；"" 算未做）。
 *      一个 { } 里有多个 OUT 时，输出是接在一起的。
 *  二、判断：' ' 改成 'Y'（合法/对）或 'N'（不合法/错）。
 *  每题后面 [ ] 是来源，「→」是讲义第几节。
 */
#include "detail.h"

int main(void)
{
    console_utf8();
    printf("环02 自测\n");

    d_section("一、猜输出");

    { char c = 'B' + 3;  OUT("%c %d", c, c); }
    GUESS(1, "");                                   /* [仿教-3-4] → 细1 */

    { OUT("%d %d", 'a' - 'A', '7' - '0' + 1); }
    GUESS(2, "");                                   /* → 细1 细2 */

    { char c1, c2;  c1 = 'A' + '7' - '4';  c2 = 'A' + '8' - '5';  OUT("%c,%d", c1, c2); }
    GUESS(3, "");                                   /* [仿配-3-60] → 细2 */

    { char ch = 'Y';  ch = (ch - 'A' + 2) % 26 + 'A';  OUT("%c", ch); }
    GUESS(4, "");                                   /* [仿配-3-47] → 细2 */

    { char ch = 'a';  while (ch < 'e') { OUT("%c", ch - 32); ch += 2; } }
    GUESS(5, "");                                   /* [仿配-3-50] → 细2 */

    { int i;  for (i = 0; i < 4; i++) OUT("%c", 'z' - i); }
    GUESS(6, "");                                   /* [仿配-3-64] → 细2 */

    { char b = 'a', c = 'A';  int i;
      for (i = 0; i < 6; i++) { if (i % 3) OUT("%c", i + b); else OUT("%c", i + c); } }
    GUESS(7, "");                                   /* [仿配-3-53] → 细2 */

    { OUT("%d%d", '\0' == 0, '0' == 0); }
    GUESS(8, "");                                   /* [配-3-49] → 细1 */

    { OUT("[%c%c%c]", 'a', '\101', '\x42'); }
    GUESS(9, "");                                   /* [配-3-41] → 细3 细4 */

    { OUT("%d %d", (int)sizeof("ab\n"), (int)strlen("ab\n")); }
    GUESS(10, "");                                  /* → 细4 细5 */

    { char d = '5';  int n = d - '0' + 10 * ('3' - '0');  OUT("%d", n); }
    GUESS(11, "");                                  /* → 细2 */

    { OUT("%o %x %X", 100, 100, 255); }
    GUESS(12, "");                                  /* → 细7 */

    { int k = -9;  OUT("%d,%o,%x", k, 1 - k, 1 - k); }
    GUESS(13, "");                                  /* [仿配-3-7] → 细7 */

    { OUT("%d %d %d", 6 & 3, 6 | 3, 6 ^ 3); }
    GUESS(14, "");                                  /* [仿配-3-76][仿配-3-83] → 细8 */

    { OUT("%d %d", 5 << 2, 37 >> 3); }
    GUESS(15, "");                                  /* [仿配-3-78][仿配-3-84] → 细8 */

    { int a = 4, b = 2, c = 3;  OUT("%d %d", a / b & c, 13 && 4); }
    GUESS(16, "");                                  /* [仿配-3-81] → 细8 */

    { int s = 21, t = 6;  s ^= s;  t ^= 3;  OUT("%d %d", s, t); }
    GUESS(17, "");                                  /* [仿配-3-90] → 细8 */

    { OUT("%d %d", -123 % 10, -123 / 10); }
    GUESS(18, "");                                  /* → 细9 */


    d_section("二、判断（Y 合法/对，N 不合法/错）");

    JUDGE(1,  ' ');   /* 'ab' 是合法的字符常量                              [配-3-39] → 细3 */
    JUDGE(2,  ' ');   /* '\x41' 是合法的字符常量                            [配-3-41] → 细3 */
    JUDGE(3,  ' ');   /* '\018' 是合法的字符常量                            [配-3-38] → 细3 */
    JUDGE(4,  ' ');   /* '\\' 是合法的字符常量                              [配-3-38] → 细3 */
    JUDGE(5,  ' ');   /* '\"' 是合法的字符常量                              [配-3-38] → 细3 */
    JUDGE(6,  ' ');   /* '' （两个连续单引号）是合法的字符常量              [配-3-34] → 细5 */
    JUDGE(7,  ' ');   /* "" （两个连续双引号）是合法的字符串常量            [配-3-34] → 细5 */
    JUDGE(8,  ' ');   /* 空字符串 "" 不占内存                               [配-3-33] → 细5 */
    JUDGE(9,  ' ');   /* '\101' 和 'A' 是同一个字符                         [配-3-35] → 细3 细4 */
    JUDGE(10, ' ');   /* char c = '\72'; c 里存了 2 个字符                  [配-3-57] → 细4 */
    JUDGE(11, ' ');   /* 字符 '0' 的值就是整数 0                            [配-3-49] → 细1 */
    JUDGE(12, ' ');   /* 'a' 和 "a" 都只占 1 个字节                         [教材3.2] → 细5 */
    JUDGE(13, ' ');   /* printf("%c", "a"); 能输出字符 a                    [配-3-62] → 细5 */
    JUDGE(14, ' ');   /* '\c' 是合法的转义字符                              [配-3-42] → 细3 */
    JUDGE(15, ' ');   /* scanf("%c%c",&a,&b); 输入「A 空格 B」，b 得到 'B'  [配-3-17] → 细6 */
    JUDGE(16, ' ');   /* scanf("%d%c",&n,&c); 输入「5 回车」，c 得到 '\n'   [教材3.4] → 细6 */
    JUDGE(17, ' ');   /* getchar() 能读入空格和回车                         [教-3-8] → 细6 */
    JUDGE(18, ' ');   /* char 型数据占 1 个字节                             [配-3-56] → 细1 */
    JUDGE(19, ' ');   /* ! 是位运算符                                       [配-3-70] → 细8 */
    JUDGE(20, ' ');   /* 位运算的对象只能是整型或字符型数据                 [配-3-68] → 细8 */
    JUDGE(21, ' ');   /* 左移一位的结果总是原数的 2 倍                      [配-3-68] → 细8 */
    JUDGE(22, ' ');   /* 13 & 5 和 13 && 5 的值相同                         [配-3-76] → 细8 */
    JUDGE(23, ' ');   /* printf("%x", 255); 输出 0xff                       [教材3.4] → 细7 */
    JUDGE(24, ' ');   /* 判断 kk 是大写字母可以写 !(kk>='A' || kk<='Z')    [配-3-44] → 细2 */
    JUDGE(25, ' ');   /* c = c - 'A' + 'a'; 能把大写字母 c 变成小写         [配-2-81] → 细2 */

    return d_summary("环02");
}
