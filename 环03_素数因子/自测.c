/*
 * ══════════════════════════════════════════════════════════════════
 *  环03 自测：猜输出 + 判断对错（运行 ring03_quiz 自动判分）
 * ══════════════════════════════════════════════════════════════════
 *  做法同前：一、把 OUT 会输出的内容写进 GUESS 的引号（空格要准，"" 算未做）；
 *            二、' ' 改成 'Y'（合法/对）或 'N'（不合法/错）。
 *  注意：这个文件里故意有「看着像错」的写法，编译器可能出黄色警告，不影响运行。
 */
#include "detail.h"

int main(void)
{
    console_utf8();
    printf("环03 自测\n");

    d_section("一、猜输出");

    { int a = 3, b = 4, c = 5;  OUT("%d %d %d", a < b, c > b > a, a < b < c); }
    GUESS(1, "");                                   /* → 细1 */

    { int a = 3, b = 4, c = 5;  OUT("%d", !(a + b) + c - 1 && b + c / 2); }
    GUESS(2, "");                                   /* [教-4-3(5)] → 细2 细4 */

    { int k1 = 5, k2 = 3;  (k1 = k1 > k2) || (k2 = k2 > k1);  OUT("%d %d", k1, k2); }
    GUESS(3, "");                                   /* [仿配-4-11] → 细3 */

    { int a = 0, b = 0, c = 0, d = 0;  (a++ || ++b) ? ++c : ++d;  OUT("%d,%d,%d,%d", a, b, c, d); }
    GUESS(4, "");                                   /* [仿配-4-57] → 细3 细7 */

    { int a = -3, b = 0;  while (a++ && ++b) ;  OUT("%d,%d", a, b); }
    GUESS(5, "");                                   /* [仿配-4-15] → 细3 细8 */

    { int n = 2, k = 1;  while (k++ && n++ > 2) ;  OUT("%d %d", k, n); }
    GUESS(6, "");                                   /* [仿配-4-16] → 细3 */

    { int x = 7;  if (x = 0) OUT("T");  OUT("F%d", x); }
    GUESS(7, "");                                   /* [仿配-4-26] → 细5 */

    { int a = 20, b = 10, c = 30;  if (a > b) a = b, b = c; c = a;  OUT("%d %d %d", a, b, c); }
    GUESS(8, "");                                   /* [仿配-4-32] → 细6 */

    { int x = 2, y = 2, z = 3;
      if (x > 1)
          if (y > x) OUT("A");
          else OUT("B");
      else
          if (z < x) OUT("C");
          else OUT("D"); }
    GUESS(9, "");                                   /* [仿配-4-35] → 细6 */

    { int s = 1, t = 5, r = 0;
      if (s > 2)
          if (t > 2) r = 1;
      else r = 2;
      OUT("%d", r); }
    GUESS(10, "");                                  /* → 细6（缩进骗人） */

    { int x = 0, y = 0;  if (!x) y++; else if (x == 0) if (x) y += 2; else y += 3;  OUT("%d", y); }
    GUESS(11, "");                                  /* [仿配-4-37] → 细6 */

    { int m = 9, a = 3, b = 2, c = 2, g, k;  g = m > 5 ? m > 8 ? 3 : 2 : 1;  k = a > b ? (b > c ? 1 : 0) : 0;
      OUT("%d %d", g, k); }
    GUESS(12, "");                                  /* [仿配-4-49] → 细7 */

    { int x;  for (x = 4; x < 7; x++) OUT((x % 2) ? "*%d" : "#%d", x); }
    GUESS(13, "");                                  /* [仿配-4-55] → 细7 */

    { int i;  for (i = 0; i < 5; i += 2) ;  OUT("%d", i); }
    GUESS(14, "");                                  /* → 细8（for 后面的分号） */

    { int y = 3, k = 3;  while (y--) ;  while (--k) ;  OUT("%d %d", y, k); }
    GUESS(15, "");                                  /* [仿配-5-7] → 细8 */

    { int i = 2;  do OUT("%d,", i); while (i-- > 1);  OUT("%d", i); }
    GUESS(16, "");                                  /* [仿配-5-17] → 细8 */

    { int i, a = 0;  for (i = 1; i < 10; i += 3) a = i;  OUT("%d,%d", i, a); }
    GUESS(17, "");                                  /* [仿配-5-36] → 细8 */

    { int i;  for (i = 1; i <= 7; i++) { if (i % 3 == 0) continue; if (i > 5) break; OUT("%d", i); }
      OUT(" %d", i); }
    GUESS(18, "");                                  /* → 细9 */

    { int x = 8;  for (; x > 0; x--) { if (x % 3) { OUT("%d,", x--); continue; } OUT("%d,", --x); } }
    GUESS(19, "");                                  /* [配-5-45] → 细9 */

    { int a = 48, b = 18, r, n = 0;  while (b != 0) { r = a % b; a = b; b = r; n++; }  OUT("%d %d", a, n); }
    GUESS(20, "");                                  /* → ⑥ 辗转相除，n 是循环次数 */


    d_section("二、判断（Y 合法/对，N 不合法/错）");

    JUDGE(1,  ' ');   /* if (表达式) 里的表达式必须是关系表达式或逻辑表达式      [配-4-19] → 细2 */
    JUDGE(2,  ' ');   /* if (a <> b) 能通过编译                                   [配-4-21] → 细2 */
    JUDGE(3,  ' ');   /* if (c = getchar()) 能通过编译                            [配-4-21] → 细2 */
    JUDGE(4,  ' ');   /* && 两边只能是整数 0 或 1                                  [配-4-1] → 细2 */
    JUDGE(5,  ' ');   /* 作为条件判断时，只有 1 才表示「真」                      [配-4-17] → 细2 */
    JUDGE(6,  ' ');   /* 10 < x < 15 能正确判断 x 是否在 10 和 15 之间             [配-4-5] → 细1 */
    JUDGE(7,  ' ');   /* 数学条件「x≥10 或 x≤0」可以写成 x >= 10 || x <= 0                   → 细1 */
    JUDGE(8,  ' ');   /* a = 0 时执行 a && ++b，b 会加 1                           [配-4-7] → 细3 */
    JUDGE(9,  ' ');   /* else 和缩进位置相同的 if 配对                             [配-4-22] → 细6 */
    JUDGE(10, ' ');   /* if (a = 1) b = 1; c = 2; else d = 3; 能通过编译           [配-4-43] → 细6 */
    JUDGE(11, ' ');   /* x、y 是 float，写 x == y 会编译出错                       [配-4-17] → 细10 */
    JUDGE(12, ' ');   /* (w) ? (-x) : (++y) 中的 (w) 等价于 (w != 0)               [配-4-46] → 细7 */
    JUDGE(13, ' ');   /* 条件运算符 ?: 是从右往左结合的                             [教材4.5] → 细7 */
    JUDGE(14, ' ');   /* do-while 的循环体至少执行一次                              [真选31·北航2018] → 细8 */
    JUDGE(15, ' ');   /* for 循环括号里的三个表达式都必须写                         [真选31·北航2018] → 细8 */
    JUDGE(16, ' ');   /* 一个 break 能同时跳出两层循环                              [真选7·武科大2019] → 细9 */
    JUDGE(17, ' ');   /* continue 的作用是结束整个循环                              [配-5-57] → 细9 */
    JUDGE(18, ' ');   /* break 可以单独用在一个 if 里（外面没有循环也没有 switch）  [真选7·武科大2019] → 细9 */
    JUDGE(19, ' ');   /* for (i = 0; i < 10; i++); 的循环体是一条空语句             [教材5.4] → 细8 */
    JUDGE(20, ' ');   /* 函数里 int sum; 没赋初值就 sum += i，结果是确定的           [配-5-48] → 细8 */
    JUDGE(21, ' ');   /* 1 是素数                                                   → ② */
    JUDGE(22, ' ');   /* 判素数时内层写 for (j = 2; j < sqrt(n); j++) 也完全正确    [真综5·华南理工2018] → ③ */
    JUDGE(23, ' ');   /* do { … } while (条件) 最后的分号可以不写                   [教材5.3] → 细8 */
    JUDGE(24, ' ');   /* while (E) 和 while (E != 0) 等价                           [配-5-1] → 细2 */

    return d_summary("环03");
}
