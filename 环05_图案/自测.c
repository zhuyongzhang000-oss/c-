/*
 * ══════════════════════════════════════════════════════════════════
 *  环05 自测：猜输出 + 判断对错（运行 ring05_quiz 自动判分）
 * ══════════════════════════════════════════════════════════════════
 *  做法同前。图案题的输出有换行：换行在 GUESS 里写成 \n，例如 "*\n**\n"。
 *  空格要写准（行首空格最容易漏）。
 */
#include "detail.h"

int main(void)
{
    int i, j;
    console_utf8();
    printf("环05 自测\n");

    d_section("一、猜输出");

    { for (i = 1; i <= 3; i++) { for (j = 1; j <= i; j++) OUT("*"); OUT("\n"); } }
    GUESS(1, "");                                   /* → ① */

    { int n = 3;  for (i = 1; i <= n; i++) { for (j = 1; j <= n - i + 1; j++) OUT("*"); OUT("\n"); } }
    GUESS(2, "");                                   /* [A-2012-2] → ① */

    { int n = 3;
      for (i = 1; i <= n; i++) { for (j = 1; j <= n - i; j++) OUT(" "); for (j = 1; j <= 2 * i - 1; j++) OUT("*"); OUT("\n"); } }
    GUESS(3, "");                                   /* → ① */

    { for (i = 1; i <= 2; i++) { for (j = 1; j <= 3; j++) OUT("*"); OUT("|"); } }
    GUESS(4, "");                                   /* → ② */

    { int cnt = 0;  for (i = 0; i < 3; i++) for (i = 0; i < 2; i++) cnt++;  OUT("%d", cnt); }
    GUESS(5, "");                                   /* → 细4 */

    { for (i = 1; i < 3; i++) { for (j = i; j < 3; j++) OUT("%d*%d=%d ", i, j, i * j); OUT("\n"); } }
    GUESS(6, "");                                   /* [仿配-5-56] → ⑦ */

    { for (i = 0; i < 3; i++) OUT("%c", 'a' + 2 * i); }
    GUESS(7, "");                                   /* → 细6 */

    { char a = '3', b = 'A';  for (i = 0; i < 5; i++) { if (i % 2) OUT("%c", a + i); else OUT("%c", b + i); } }
    GUESS(8, "");                                   /* [仿配-3-66] → 细6 */

    { OUT("[%3d][%-3d][%2d]", 5, 5, 123); }
    GUESS(9, "");                                   /* → 细2 */

    { for (i = 1; i <= 7; i++) { OUT("%d", i); if (i % 3 == 0) OUT("\n"); } }
    GUESS(10, "");                                  /* [仿配-4-34] → 细3 */

    { int x = 0;  for (i = 0; i < 2; i++) { x++; for (j = 0; j <= 2; j++) { if (j % 2) continue; x++; } x++; }
      OUT("%d", x); }
    GUESS(11, "");                                  /* [仿配-5-52] → 细7 */

    { int m = 20;  for (i = 1; i <= 3; i++) for (j = 3; j <= i; j++) m = m % j;  OUT("%d", m); }
    GUESS(12, "");                                  /* [仿配-5-55] → 细7 */

    { int k;  for (k = 1; k <= 10; k++) { if (k++ % 3 == 0) OUT("%d ", k); } }
    GUESS(13, "");                                  /* [仿配-2-118] → 细5 */

    { int a[6][6];
      for (i = 0; i < 6; i++) { a[i][0] = a[i][i] = 1; for (j = 1; j < i; j++) a[i][j] = a[i - 1][j - 1] + a[i - 1][j]; }
      OUT("%d %d", a[4][2], a[5][2]); }
    GUESS(14, "");                                  /* [A-2024-2] → ⑥ */

    { int n = 3, total = 0;
      for (i = 1; i <= n; i++) total += 2 * i - 1;
      for (i = n - 1; i >= 1; i--) total += 2 * i - 1;
      OUT("%d", total); }
    GUESS(15, "");                                  /* → ④ 菱形一共几个星号 */

    { for (i = 0; i < 4; i++) OUT("%c", '9' - 2 * i); }
    GUESS(16, "");                                  /* [仿配-3-65] → 细6 */


    d_section("二、判断（Y 合法/对，N 不合法/错）");

    JUDGE(1,  ' ');   /* puts("abc"); 输出 abc 后会自动换行                     [教材3.5] → 细1 */
    JUDGE(2,  ' ');   /* putchar("A"); 能输出字符 A                             [配-3-62] → 细1 */
    JUDGE(3,  ' ');   /* printf("%2d", 12345); 只输出 12                        [教材3.4] → 细2 */
    JUDGE(4,  ' ');   /* %-5d 表示右对齐                                         [教材3.4] → 细2 */
    JUDGE(5,  ' ');   /* 打印图案时，换行语句应该写在内层循环里面                          → ③ */
    JUDGE(6,  ' ');   /* 内外两层循环用同一个循环变量 i 不会出问题                         → 细4 */
    JUDGE(7,  ' ');   /* n 行金字塔，第 i 行（i 从 1 开始）有 2i-1 个星号                  → ① */
    JUDGE(8,  ' ');   /* int a[6][6]; 的最后一个元素是 a[6][6]                   [教材6.2] → ⑥ */
    JUDGE(9,  ' ');   /* putchar(65); 输出字符 A                                 [配-3-62] → 细1 */
    JUDGE(10, ' ');   /* for 循环的循环体里不允许再修改循环变量                  [配-2-118] → 细5 */
    JUDGE(11, ' ');   /* %c 也可以指定宽度，例如 %3c                             [教材3.4] → 细2 */
    JUDGE(12, ' ');   /* 杨辉三角第 i 行（i 从 0 开始数）有 i+1 个数                       → ⑥ */
    JUDGE(13, ' ');   /* 外层循环 3 次、内层循环 4 次，内层循环体一共执行 12 次  [教材5.5] → 细7 */
    JUDGE(14, ' ');   /* printf("\n"); 和 putchar('\n'); 的效果相同              [教材3.5] → 细1 */
    JUDGE(15, ' ');   /* puts 输出字符串时不会自动换行                           [教材3.5] → 细1 */

    return d_summary("环05");
}
