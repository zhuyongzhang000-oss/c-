    d_section("一、猜输出");

    { int a[5] = {1, 2};  OUT("%d %d %d", a[1], a[2], a[4]); }
    GUESS(1, "");                                   /* → 细2 */

    { int a[] = {3, 1, 4, 1, 5};  OUT("%d %d", (int)(sizeof(a) / sizeof(a[0])), (int)sizeof(a)); }
    GUESS(2, "");                                   /* → 细5 */

    { int m[] = {5, 4, 3, 2, 1}, k = 4, x;  x = m[--k];  OUT("%d %d %d", x, m[m[k]], m[2 * 2]); }
    GUESS(3, "");                                   /* [仿配-6-10] → 细7 */

    { int s[6] = {1, 2, 2, 3, 3, 3}, c[4] = {0};  for (i = 0; i < 6; i++) c[s[i]]++;
      OUT("%d %d %d", c[1], c[2], c[3]); }
    GUESS(4, "");                                   /* [仿配-6-12] → 细7 */

    { int a[5] = {1, 2, 3, 4, 5};  for (i = 0; i < 5 / 2; i++) { t = a[i]; a[i] = a[4 - i]; a[4 - i] = t; }
      for (i = 0; i < 5; i++) OUT("%d ", a[i]); }
    GUESS(5, "");                                   /* [配-6-13] → 细8 */

    { int a[5] = {1, 2, 3, 4, 5};  for (i = 0; i < 5; i++) { t = a[i]; a[i] = a[4 - i]; a[4 - i] = t; }
      for (i = 0; i < 5; i++) OUT("%d ", a[i]); }
    GUESS(6, "");                                   /* → 细8 */

    { int a[4] = {5, 1, 4, 2};  for (j = 0; j < 3; j++) if (a[j] > a[j + 1]) { t = a[j]; a[j] = a[j + 1]; a[j + 1] = t; }
      for (i = 0; i < 4; i++) OUT("%d ", a[i]); }
    GUESS(7, "");                                   /* 冒泡只走一趟 → ① */

    { int a[] = {1, 2, 3, 4, 5, 6, 7, 8, 9}, s = 0, k;  for (k = 0; k < 8; k += 2) s += a[k];  OUT("%d", s); }
    GUESS(8, "");                                   /* [仿配-6-21] → ⑧ */

    { int a[7] = {1, 3, 5, 7, 9, 11, 13}, left = 0, right = 6, mid, x = 11, steps = 0, pos = -1;
      while (left <= right) { mid = (left + right) / 2; steps++;
          if (a[mid] == x) { pos = mid; break; } else if (a[mid] < x) left = mid + 1; else right = mid - 1; }
      OUT("%d %d", pos, steps); }
    GUESS(9, "");                                   /* [A-2019-4] → ③ */

    { int a[7] = {1, 3, 5, 7, 9, 11, 13}, left = 0, right = 6, mid, x = 4, pos = -1;
      while (left <= right) { mid = (left + right) / 2;
          if (a[mid] == x) { pos = mid; break; } else if (a[mid] < x) left = mid + 1; else right = mid - 1; }
      OUT("%d %d %d", pos, left, right); }
    GUESS(10, "");                                  /* 找不到时 left、right 停在哪 → ③ */

    { int a[5] = {1, 3, 5, 7}, n = 4, x = 4, pos = 2;
      for (i = n; i > pos; i--) a[i] = a[i - 1];  a[pos] = x;  n++;
      for (i = 0; i < n; i++) OUT("%d ", a[i]); }
    GUESS(11, "");                                  /* [教-6-4] → ⑤ */

    { int a[5] = {1, 3, 5, 7}, n = 4, x = 4, pos = 2;
      for (i = pos; i < n; i++) a[i + 1] = a[i];  a[pos] = x;  n++;
      for (i = 0; i < n; i++) OUT("%d ", a[i]); }
    GUESS(12, "");                                  /* 搬的方向反了 → ⑤ */

    { int a[3] = {1, 4, 9}, b[4] = {2, 3, 10, 12}, c[7], k = 0;  i = j = 0;
      while (i < 3 && j < 4) c[k++] = a[i] <= b[j] ? a[i++] : b[j++];
      for (t = 0; t < k; t++) OUT("%d ", c[t]); }
    GUESS(13, "");                                  /* 忘了收尾 → ⑥ */

    { int a[5] = {3, 9, 2, 9, 1}, k1 = 0, k2 = 0;
      for (i = 1; i < 5; i++) { if (a[i] > a[k1]) k1 = i; if (a[i] >= a[k2]) k2 = i; }
      OUT("%d %d", k1, k2); }
    GUESS(14, "");                                  /* > 和 >= 找到的是哪个最大值 → ② */

    { int a[10] = {0};  for (i = 0; i < 10; i++) a[i] = i * i;  OUT("%d", a[a[2] + 1]); }
    GUESS(15, "");                                  /* → 细7 */


    d_section("二、判断（Y 合法/对，N 不合法/错）");

    JUDGE(1,  ' ');   /* int a[4] = {1, 2, 3, 4, 5}; 编译时会忽略多余的初值      [配-6-4] → 细2 */
    JUDGE(2,  ' ');   /* int a[] = {0}; 能通过编译                              [配-6-2] → 细2 */
    JUDGE(3,  ' ');   /* int a[8] = {0}; 让 8 个元素都是 0                      [配-6-4] → 细2 */
    JUDGE(4,  ' ');   /* int n = 5; int a[n]; 按教材和考试是正确的数组定义      [配-6-5] → 细1 */
    JUDGE(5,  ' ');   /* #define N 5 之后 int a[N]; 是正确的数组定义            [配-6-7] → 细1 */
    JUDGE(6,  ' ');   /* int a[2 + 3]; 能通过编译                               [配-6-9] → 细1 */
    JUDGE(7,  ' ');   /* int a[0..10]; 能通过编译                               [配-6-8] → 细1 */
    JUDGE(8,  ' ');   /* 数组下标可以是浮点数，例如 a[1.5]                       [配-6-3] → 细3 */
    JUDGE(9,  ' ');   /* int a[5]; 写 a[5] = 1; 编译器会报错                     [教材6.1] → 细3 */
    JUDGE(10, ' ');   /* int a[5], b[5]; 写 a = b; 可以把 b 整个复制给 a         [配-6-2] → 细4 */
    JUDGE(11, ' ');   /* int a[5] = {, 1, 2}; 可以跳过前面的元素给后面赋初值     [配-6-4] → 细2 */
    JUDGE(12, ' ');   /* 一条语句可以定义多个数组，如 int a[3], b[4];            [配-6-1] → 细1 */
    JUDGE(13, ' ');   /* 数组的元素在内存中连续存放                             [配-6-1] → 细5 */
    JUDGE(14, ' ');   /* 在被调函数里用 sizeof(a)/sizeof(a[0]) 能求出形参数组的长度 [教材7.7] → 细5 */
    JUDGE(15, ' ');   /* 数组作函数参数时，函数里修改元素会影响主函数里的数组    [配-6-38] → 细6 */
    JUDGE(16, ' ');   /* 函数里定义 int a[5]; 不初始化，5 个元素都是 0           [教材6.1] → 细10 */
    JUDGE(17, ' ');   /* 二分查找要求数组已经有序                               → ③ */
    JUDGE(18, ' ');   /* 冒泡排序 n 个数最多需要 n-1 趟                          → ① */
    JUDGE(19, ' ');   /* 有序插入时应该从前往后搬动元素                         [教-6-4] → ⑤ */
    JUDGE(20, ' ');   /* 判断奇数写 a[i] % 2 == 1，对负数也正确                  → ⑦ */

