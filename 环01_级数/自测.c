/*
 * ══════════════════════════════════════════════════════════════════
 *  环01 自测：猜输出 + 判断对错（运行 ring01_quiz 自动判分）
 * ══════════════════════════════════════════════════════════════════
 *  先读完 讲义.html 再做。不要回去翻讲义，凭脑子做，错了才有用。
 *
 *  一、猜输出：每个 { } 里是一段代码，OUT 和 printf 用法一样（只是先不打印，留着比对）。
 *      把你认为 OUT 会输出的内容写进下一行 GUESS 的引号里。
 *      空格要写准，"" 不填算未做（未做不揭晓答案）。
 *  二、判断：把 ' ' 改成 'Y'（合法 / 说法对）或 'N'（不合法 / 说法错）。
 *      「合法」指按 C 语言标准和考试口径能通过编译。
 *  运行后：对的显示「对」；错的显示正确答案和理由。最后一行可以发给 chat。
 *
 *  每题后面 [ ] 是来源或改编自哪道题；对应讲义第几节写在「→」后面。
 */
#include "detail.h"

int main(void)
{
    console_utf8();
    printf("环01 自测\n");

    d_section("一、猜输出");

    { int a = 7, b = 2;  OUT("%d %d %d", a / b, a % b, -a / b); }
    GUESS(1, "");                                   /* → 细5 */

    { OUT("%d %d", -7 % 3, 7 % -3); }
    GUESS(2, "");                                   /* → 细5 */

    { double d = 7 / 2;  OUT("%.1f %.1f", d, 7 / 2.0); }
    GUESS(3, "");                                   /* → 细6 */

    { int x = 12, y = 8, z;  z = 0.9 + x / y;  OUT("%d", z); }
    GUESS(4, "");                                   /* [配-2-72] → 细6 */

    { OUT("%d", (int)((double)11 / 4) - 11 % 4); }
    GUESS(5, "");                                   /* [仿配-2-73] → 细6 */

    { OUT("%.1f", 4.5 - 7 / 2 + 0.5 + 7 % 3); }
    GUESS(6, "");                                   /* [仿配-2-75] → 细5 细6 */

    { OUT("%d %d", (int)2.7 * 2, (int)(2.7 * 2)); }
    GUESS(7, "");                                   /* [仿配-2-84] → 细6 */

    { int k = 017, v;  v = k++;  OUT("%d %d %d", v, k, 0x1A); }
    GUESS(8, "");                                   /* [仿配-2-47] → 细2 细8 */

    { int i = 3, a, b;  a = ++i;  b = i--;  OUT("%d %d %d", a, b, i); }
    GUESS(9, "");                                   /* → 细8 */

    { int x, y, z;  x = y = 2;  z = x--, ++y, y++;  OUT("%d,%d,%d", x, y, z); }
    GUESS(10, "");                                  /* [仿配-2-115] → 细9 */

    { int sum, pad, pAd;  sum = pad = 5;  pAd = ++sum, pAd++, ++pad;  OUT("%d %d %d", sum, pAd, pad); }
    GUESS(11, "");                                  /* [配-2-117] → 细9 */

    { int x = 4, y = 7;  x *= x + 1;  y -= y + 3;  OUT("%d %d", x, y); }
    GUESS(12, "");                                  /* [仿配-2-103] → 细7 */

    { int x, y = 5;  x = y == 5;  OUT("%d %d", x, y == 4); }
    GUESS(13, "");                                  /* [配-2-100] → 细7 */

    { OUT("%d%6.2f|", 7, 3.14159); }
    GUESS(14, "");                                  /* [仿配-3-10] → 细10 */

    { OUT("%3d,%o,%x", 20, 20, 20); }
    GUESS(15, "");                                  /* [仿配-3-6] → 细10 */

    { OUT("[%-4d][%04d][%.3f]", 7, 7, 3.14159); }
    GUESS(16, "");                                  /* → 细10 */

    { OUT("%e", 1234.5); }
    GUESS(17, "");                                  /* → 细10 */

    { int a = 2, c = 5;  OUT("a=%%d,c=%d", a, c); }
    GUESS(18, "");                                  /* [仿配-3-11] → 细10 */


    d_section("二、判断（Y 合法/对，N 不合法/错）");

    JUDGE(1,  ' ');   /* _8_ 是合法的变量名                              [真选43·川大2017] → 细1 */
    JUDGE(2,  ' ');   /* 2a 是合法的变量名                               [配-2-25] → 细1 */
    JUDGE(3,  ' ');   /* Int 是合法的变量名                              [仿真选43] → 细1 */
    JUDGE(4,  ' ');   /* stu-code 是合法的变量名                         [真选1·武科大2019] → 细1 */
    JUDGE(5,  ' ');   /* 函数里写 int printf; 能通过编译                 [配-2-41] → 细1 */
    JUDGE(6,  ' ');   /* 0118 是合法的整型常量                           [配-2-35] → 细2 */
    JUDGE(7,  ' ');   /* 0xAbc 是合法的整型常量                          [配-2-55] → 细2 */
    JUDGE(8,  ' ');   /* 2e1.5 是合法的实型常量                          [配-2-58] → 细3 */
    JUDGE(9,  ' ');   /* .5E3 是合法的实型常量                           [配-2-56] → 细3 */
    JUDGE(10, ' ');   /* E5 是合法的实型常量                             [配-2-56] → 细3 */
    JUDGE(11, ' ');   /* C 程序里可以直接写二进制常量 0b101              [配-2-45] → 细2 */
    JUDGE(12, ' ');   /* a、b 都没定义过，int a = b = 1; 能通过编译      [配-2-39] → 细7 */
    JUDGE(13, ' ');   /* x、y 已定义，x + 1 = y; 能通过编译              [配-2-91] → 细7 */
    JUDGE(14, ' ');   /* a、b、c 已定义，a = (b = 3) = 1; 能通过编译     [配-2-92] → 细7 */
    JUDGE(15, ' ');   /* k 已定义，k = int(3.5); 能通过编译              [配-2-101] → 细6 */
    JUDGE(16, ' ');   /* double z = 7.5 % 2; 能通过编译                  [配-2-65] → 细5 */
    JUDGE(17, ' ');   /* i 已定义，(i + 1)++; 能通过编译                 [配-2-80] → 细8 */
    JUDGE(18, ' ');   /* (int)3.99 的值是 4                              [教材3.2] → 细6 */
    JUDGE(19, ' ');   /* -17 % 5 的值是 -2                               [教材3.2] → 细5 */
    JUDGE(20, ' ');   /* 函数里 int k; 没赋值，k 的值就是 0              [配-2-51] → 细4 */
    JUDGE(21, ' ');   /* 表达式 'A' + 10 + 3.14 的类型是 double           [配-2-62] → 细6 */
    JUDGE(22, ' ');   /* sizeof 是一个库函数                             [教材3.2] → 细4 */
    JUDGE(23, ' ');   /* scanf("%d,%d", &a, &b); 输入 3 5 回车，b 能得到 5  [配-3-15] → 细11 */
    JUDGE(24, ' ');   /* double x; 用 scanf("%f", &x); 能正确读入 x      [配-3-28] → 细11 */
    JUDGE(25, ' ');   /* scanf("%5.2f", &x); 可以限定读入两位小数         [真选3·武科大2019] → 细11 */
    JUDGE(26, ' ');   /* a += a -= a * a; 在标准 C 里有唯一确定的结果     [川师卷2019-20 一-8] → 细12 */

    return d_summary("环01");
}
